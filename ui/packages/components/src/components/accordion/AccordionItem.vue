<script lang="ts" setup>
import {
  AccordionContent,
  AccordionHeader,
  AccordionItem as AccordionItemRoot,
  AccordionTrigger,
} from "reka-ui";
import { onMounted, shallowRef } from "vue";
import { IconArrowRight } from "../../icons/icons";
import type { VAccordionHeaderTag } from "./types";

withDefaults(
  defineProps<{
    /**
     * Unique identifier of the item within its accordion.
     */
    value: string;
    /**
     * Plain text shown in the trigger. Use the `trigger` slot for custom
     * content.
     */
    title?: string;
    disabled?: boolean;
    /**
     * Heading element used to wrap the trigger. Defaults to `h3`; use `div`
     * when the accordion should not add an entry to the document outline.
     */
    headerAs?: VAccordionHeaderTag;
    /**
     * Overrides the root `unmountOnHide` for this item.
     */
    unmountOnHide?: boolean;
    /**
     * Keeps the content mounted even when the item is closed and the root
     * unmounts hidden content.
     */
    forceMount?: boolean;
    triggerClass?: string | string[] | Record<string, boolean>;
    contentClass?: string | string[] | Record<string, boolean>;
  }>(),
  {
    title: undefined,
    disabled: false,
    headerAs: "h3",
    unmountOnHide: undefined,
    forceMount: false,
    triggerClass: undefined,
    contentClass: undefined,
  }
);

// Reka 2.11 stores the generated content id on a non-reactive context object.
// The trigger renders before the content, so `aria-controls` is empty until
// the trigger renders again. Updating this attribute after mount refreshes the
// trigger with the id generated by its sibling content.
const contentReady = shallowRef(false);
const animating = shallowRef(false);
onMounted(() => {
  contentReady.value = true;
});

function onContentAnimationStart() {
  animating.value = true;
}

function onContentAnimationEnd() {
  animating.value = false;
}
</script>

<template>
  <AccordionItemRoot
    v-slot="{ open }"
    :value="value"
    :disabled="disabled"
    :unmount-on-hide="unmountOnHide"
    class="v-accordion-item"
  >
    <AccordionHeader :as="headerAs" class="v-accordion-header">
      <AccordionTrigger
        :class="['v-accordion-trigger', triggerClass]"
        :data-content-ready="contentReady || undefined"
      >
        <slot name="trigger" :open="open">
          <span class="v-accordion-title">{{ title }}</span>
        </slot>
        <slot name="icon" :open="open">
          <IconArrowRight class="v-accordion-icon" />
        </slot>
      </AccordionTrigger>
    </AccordionHeader>
    <AccordionContent
      :force-mount="forceMount"
      :class="[
        'v-accordion-content',
        { 'v-accordion-content--animating': animating },
      ]"
      @animationstart.self="onContentAnimationStart"
      @animationend.self="onContentAnimationEnd"
      @animationcancel.self="onContentAnimationEnd"
    >
      <div :class="contentClass" class="v-accordion-content-inner">
        <slot :open="open" />
      </div>
    </AccordionContent>
  </AccordionItemRoot>
</template>

