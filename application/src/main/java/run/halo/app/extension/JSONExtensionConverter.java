package run.halo.app.extension;

import static run.halo.app.extension.ExtensionStoreUtil.buildStoreName;
import static run.halo.app.extension.Unstructured.OBJECT_MAPPER;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.networknt.schema.Schema;
import com.networknt.schema.SchemaRegistry;
import com.networknt.schema.dialect.OpenApi30;
import java.io.IOException;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentMap;
import lombok.Getter;
import lombok.extern.slf4j.Slf4j;
import org.springframework.context.event.EventListener;
import org.springframework.stereotype.Component;
import org.springframework.util.Assert;
import run.halo.app.extension.event.SchemeRemovedEvent;
import run.halo.app.extension.exception.ExtensionConvertException;
import run.halo.app.extension.exception.SchemaViolationException;
import run.halo.app.extension.store.ExtensionStore;

/**
 * JSON implementation of ExtensionConverter.
 *
 * @author johnniang
 */
@Slf4j
@Component
class JSONExtensionConverter implements ExtensionConverter {

    /**
     * Schema registry for creating validators. The OpenAPI 3.0 dialect is required because the schemas are generated by
     * swagger-core and may contain the {@code nullable} keyword.
     *
     * <p>Intentionally an instance field: Halo restarts by recreating the application context in the same JVM, and the
     * registry (including its schema cache) must not outlive the context that owns the schemes.
     */
    private final SchemaRegistry schemaRegistry = SchemaRegistry.withDefaultDialect(OpenApi30.getInstance());

    @Getter
    public ObjectMapper objectMapper;

    private final SchemeManager schemeManager;

    private final ConcurrentMap<Scheme, Schema> validatorMap = new ConcurrentHashMap<>();

    public JSONExtensionConverter(SchemeManager schemeManager) {
        this.schemeManager = schemeManager;
        setObjectMapper(OBJECT_MAPPER);
    }

    /**
     * Sets ObjectMapper.
     *
     * @param objectMapper the object mapper, must not be null
     */
    void setObjectMapper(ObjectMapper objectMapper) {
        Assert.notNull(objectMapper, "ObjectMapper must not be null");
        this.objectMapper = objectMapper;
    }

    @Override
    public <E extends Extension> ExtensionStore convertTo(E extension) {
        var gvk = extension.groupVersionKind();
        var scheme = schemeManager.get(gvk);

        try {
            var convertedExtension = Optional.of(extension)
                    .map(item -> scheme.type().isAssignableFrom(item.getClass())
                            ? item
                            : objectMapper.convertValue(item, scheme.type()))
                    .orElseThrow();

            var extensionJsonNode = objectMapper.valueToTree(convertedExtension);
            var validator = getValidator(scheme);
            var errors = validator.validate(extensionJsonNode);
            if (!errors.isEmpty()) {
                log.debug("Failed to validate Extension: {}, and errors were: {}", extension.getClass(), errors);
                throw new SchemaViolationException(extension.groupVersionKind(), errors);
            }

            var version = extension.getMetadata().getVersion();
            var storeName = buildStoreName(scheme, extension.getMetadata().getName());
            var data = objectMapper.writeValueAsBytes(extensionJsonNode);
            return new ExtensionStore(storeName, data, version);
        } catch (IOException e) {
            throw new ExtensionConvertException("Failed write Extension as bytes", e);
        }
    }

    @Override
    public <E extends Extension> E convertFrom(Class<E> type, ExtensionStore extensionStore) {
        try {
            var extension = objectMapper.readValue(extensionStore.getData(), type);
            extension.getMetadata().setVersion(extensionStore.getVersion());
            return extension;
        } catch (IOException e) {
            throw new ExtensionConvertException("Failed to read Extension " + type + " from bytes", e);
        }
    }

    @EventListener
    void onSchemeRemovedEvent(SchemeRemovedEvent event) {
        var removed = validatorMap.remove(event.getScheme());
        if (log.isDebugEnabled()) {
            if (removed == null) {
                log.debug(
                        "No available validator found while removing validator for scheme: {}",
                        event.getScheme().groupVersionKind());
            } else {
                log.debug(
                        "Removed schema validator {} for scheme: {}",
                        removed,
                        event.getScheme().groupVersionKind());
            }
        }
    }

    private Schema getValidator(Scheme scheme) {
        return validatorMap.computeIfAbsent(scheme, s -> {
            var validator = schemaRegistry.getSchema(s.openApiSchema());
            if (log.isDebugEnabled()) {
                log.debug("Created schema validator {} for scheme: {}", validator, scheme.groupVersionKind());
            }
            return validator;
        });
    }
}
